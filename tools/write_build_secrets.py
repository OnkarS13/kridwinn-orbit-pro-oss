#!/usr/bin/env python3
"""
Prepare build-time secrets for Kridwinn Orbit Pro.

Reads secrets from environment variables and writes:
  - pages/licensing/_build_secrets.py   (compiled into the app, git-ignored)
  - secure_config/firebase_creds.enc    (from FIREBASE_CREDS_ENC_B64, optional)
  - secure_config/licensing_config.enc  (from LICENSING_CONFIG_ENC_B64, optional)

Required environment variables:
  KRIDWINN_CONFIG_KEY, KRIDWINN_ACTIVATION_SALT, KRIDWINN_ADMIN_SALT
Optional environment variables:
  FIREBASE_CREDS_ENC_B64, LICENSING_CONFIG_ENC_B64

Usage:
  python tools/write_build_secrets.py
"""

import base64
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SECRETS_MODULE = ROOT / "pages" / "licensing" / "_build_secrets.py"
SECURE_DIR = ROOT / "secure_config"

REQUIRED = ("KRIDWINN_CONFIG_KEY", "KRIDWINN_ACTIVATION_SALT", "KRIDWINN_ADMIN_SALT")
ENC_FILES = {
    "FIREBASE_CREDS_ENC_B64": "firebase_creds.enc",
    "LICENSING_CONFIG_ENC_B64": "licensing_config.enc",
}


def main() -> int:
    missing = [name for name in REQUIRED if not os.environ.get(name)]
    if missing:
        print(f"ERROR: missing required environment variables: {', '.join(missing)}", file=sys.stderr)
        return 1

    lines = ['"""Generated by tools/write_build_secrets.py - DO NOT COMMIT."""', ""]
    for name in REQUIRED:
        lines.append(f"{name} = {os.environ[name]!r}")
    SECRETS_MODULE.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {SECRETS_MODULE.relative_to(ROOT)}")

    SECURE_DIR.mkdir(exist_ok=True)
    for env_name, file_name in ENC_FILES.items():
        value = os.environ.get(env_name)
        if not value:
            print(f"Skipped secure_config/{file_name} ({env_name} not set)")
            continue
        (SECURE_DIR / file_name).write_bytes(base64.b64decode(value))
        print(f"Wrote secure_config/{file_name}")

    return 0


if __name__ == "__main__":
    sys.exit(main())
